"""Build web/js/india-map.js: simplified SVG outlines of India's states, for the dashboard's region map.

    pip install shapely
    python tools/build_india_map.py path/to/india.geojson

Input is the district-level GeoJSON from https://github.com/udit-001/india-maps-data (geojson/india.geojson),
which follows the Survey of India external boundary. Districts are merged into states and union territories,
simplified, and projected with a simple equal-area-ish projection. The output is one SVG path per state.
Run it once; the result is committed, so the site needs no build step.
"""

import json
import math
import sys
from pathlib import Path

from shapely.geometry import MultiPolygon, Polygon, shape
from shapely.ops import unary_union

OUT = Path(__file__).resolve().parent.parent / "web" / "js" / "india-map.js"
LON0, LAT0 = 82.5, 22.0   # projection centre
TOLERANCE = 0.035         # degrees; larger = lighter file, blockier coast
MIN_AREA = 0.004          # drop specks smaller than this (square degrees) after simplifying
SCALE = 17.0              # SVG units per degree


def project(lon, lat):
    return (lon - LON0) * math.cos(math.radians(LAT0)) * SCALE, -(lat - LAT0) * SCALE


def ring_path(ring):
    points = [project(x, y) for x, y in ring.coords]
    return "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in points[:-1]) + "Z"


def main(source):
    by_state = {}
    for feature in json.loads(Path(source).read_text(encoding="utf-8"))["features"]:
        geometry = shape(feature["geometry"])
        by_state.setdefault(feature["properties"]["st_nm"], []).append(geometry if geometry.is_valid else geometry.buffer(0))
    states = {}
    for name, parts in sorted(by_state.items()):
        merged = unary_union(parts).simplify(TOLERANCE, preserve_topology=True)
        polygons = [merged] if isinstance(merged, Polygon) else list(merged.geoms) if isinstance(merged, MultiPolygon) else []
        polygons = [p for p in polygons if p.area >= MIN_AREA] or polygons[:1]
        path = "".join(ring_path(p.exterior) + "".join(ring_path(h) for h in p.interiors) for p in polygons)
        states[name] = {"d": path}
    box = unary_union([g for parts in by_state.values() for g in parts]).bounds
    (x0, y1), (x1, y0) = project(box[0], box[1]), project(box[2], box[3])
    width, height = x1 - x0, y1 - y0
    payload = {"viewBox": [round(x0, 1), round(y0, 1), round(width, 1), round(height, 1)], "states": states}
    OUT.write_text("// Generated by tools/build_india_map.py from Survey of India boundaries. Do not edit.\n"
                   f"export const INDIA = {json.dumps(payload, separators=(',', ':'))};\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB, {len(states)} states)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "india.geojson")
