"""The decision clock: how far a forecast made on each day can be trusted, from cold to two weeks after launch.

A licence is signed months before the Japanese premiere and a dub is ordered weeks after it, so the question is
not only "what will it do?" but "how much do we know today?". For each day below the Blend is refitted with only
the data dated before that day (the stages' windows cut off the day before, see features.stage), trained on
2019-2023 and scored on the 2024 titles and on the rolling seasons, as evaluate.py scores the three stages.
Each day also gets its 80% range from the misses on past seasons, and every 2024 title its forecast on each
day: how it would have moved as the buzz came in.

Day 0 and later are nowcasts: from the premiere on, the inputs fall inside the 28 days the index measures.
The clock describes our model only; at a stage where a simple rule won (gate G4) the verdicts still use the rule.

    python -m yosoku.clock          # writes reports/clock.md and reports/clock.json
"""

import argparse
import json

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from yosoku.data import add_folder_arguments, folder
from yosoku.evaluate import MIN_TARGET, MIN_TRAIN, bootstrap, fmt, prepare, scores
from yosoku.models import Blend, conformal_width, lookalikes, stacked_inputs
from yosoku.split import guard_test, rolling_folds, split_of

DAYS = [-49, -42, -35, -28, -21, -14, -7, 0, 3, 7, 14]  # the day a forecast is made: it sees data up to the day before
STAGES = {-28: "t-28", 7: "t+7"}  # days that are also verdict stages


def cutoff(day):
    """The moment features.stage takes for a clock day: "cold", or the last day it may use."""
    return "cold" if day == "cold" else day - 1


def number(x):
    return None if x is None or pd.isna(x) else float(x)


def blend(features, titles, labels, train, target, looks):
    X_train, X_target, _ = stacked_inputs(features, titles, labels, train, target, looks)
    return Blend().fit(X_train, labels.loc[train]).predict(X_target)


def run(titles, labels, features):
    """{"days": [one row per day], "titles": {anilist_id: [forecast per day]}} for the 2024 validation titles."""
    split = split_of(titles)
    train = split.index[split == "train"].intersection(labels.index)
    validate = split.index[split == "validate"].intersection(labels.index)
    guard_test(validate, titles, final=False)
    folds = [(name, tr.intersection(labels.index), te.intersection(labels.index)) for name, tr, te in rolling_folds(titles)]
    folds = [(name, tr, te) for name, tr, te in folds if len(tr) >= MIN_TRAIN and len(te) >= MIN_TARGET]
    # The lookalikes depend only on which titles train and which are forecast, so fit them once for every day.
    looks = {"2024": lookalikes(titles, labels, train, validate)}
    looks.update({name: lookalikes(titles, labels, tr, te) for name, tr, te in folds})

    rows, paths = [], {}
    for day in ["cold", *DAYS]:
        f = features[cutoff(day)]
        val = blend(f, titles, labels, train, validate, looks["2024"])
        seasons, misses = [], []
        for name, tr, te in folds:
            pred = blend(f, titles, labels, tr, te, looks[name])
            both = pd.concat([pred.rename("p"), labels.loc[te].rename("a")], axis=1).dropna()
            seasons.append(spearmanr(both["p"], both["a"]).statistic)
            if not name.endswith("2024"):  # the range is set before the year it is checked on
                misses += list(both["a"] - both["p"])
        actual = labels.loc[validate]
        s = scores(val, actual)
        low, high = bootstrap(val, actual)
        width = conformal_width(misses)
        stats = {"spearman": s["spearman"], "low": low, "high": high, "top20": s["top20"], "mae": s["mae"],
                 "rolling": np.nanmean(seasons), "width": width, "coverage": ((val - actual).abs() <= width).mean()}
        rows.append({"day": day, "stage": "cold" if day == "cold" else STAGES.get(day), "nowcast": day != "cold" and day >= 0,
                     "seasons": len(seasons), **{k: number(v) for k, v in stats.items()}})
        for anilist_id, value in val.items():
            paths.setdefault(int(anilist_id), []).append(round(float(value), 1))
    return {"days": rows, "titles": paths}


def report(result):
    lines = ["# The decision clock", "", "Generated by `python -m yosoku.clock`; do not edit by hand.", "",
             "The Blend refitted for each day, using only data dated before it, trained on 2019–2023 and scored on the "
             "2024 titles. From day 0 on it is a nowcast: its inputs fall inside the 28 days being measured.", "",
             "| Forecast made on | Spearman 2024 (95% interval) | Top-20% hit | MAE | Rolling seasons | 80% range | Range held |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in result["days"]:
        when = "cold (no buzz)" if r["day"] == "cold" else f"day {r['day']:+d}" + (f" ({r['stage']})" if r["stage"] else "")
        lines.append(f"| {when}{' · nowcast' if r['nowcast'] else ''} | {fmt(r['spearman'])} ({fmt(r['low'])} to {fmt(r['high'])}) | "
                     f"{fmt(r['top20'])} | {fmt(r['mae'], 1)} | {fmt(r['rolling'])} over {r['seasons']} | ± {fmt(r['width'], 1)} | "
                     f"{'–' if r['coverage'] is None else format(r['coverage'], '.0%')} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_folder_arguments(parser)
    args = parser.parse_args()
    data_dir, out_dir = folder(args.data_dir), folder(args.out_dir)
    titles, labels, features = prepare(data_dir, out_dir, moments=[cutoff(d) for d in ["cold", *DAYS]])
    result = run(titles, labels, features)
    (out_dir / "reports").mkdir(parents=True, exist_ok=True)
    (out_dir / "reports" / "clock.md").write_text(report(result), encoding="utf-8")
    (out_dir / "reports" / "clock.json").write_text(json.dumps(result, indent=1, allow_nan=False), encoding="utf-8")
    print("Wrote reports/clock.md")


if __name__ == "__main__":
    main()
