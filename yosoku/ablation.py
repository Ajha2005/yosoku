"""What each signal is worth: retrain the Blend without one group of inputs at a time and see how much it loses.

For T-28 and T+7 (the cold forecast has no buzz signals), the Blend is refitted with each group below left out,
then scored the way evaluate.py scores it: rank correlation (Spearman) on the 2024 validation titles, and its
average over the rolling seasons (Winter 2020 to Fall 2024), which rests on many more titles. A group whose
removal costs a lot of correlation carries real information; one that costs nothing is noise for this question.

    python -m yosoku.ablation             # writes reports/ablation.md and reports/ablation.json
"""

import argparse
import json

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from yosoku.data import add_folder_arguments, folder
from yosoku.evaluate import MIN_TARGET, MIN_TRAIN, bootstrap, fmt, prepare
from yosoku.models import Blend, stacked_inputs
from yosoku.split import guard_test, rolling_folds, split_of

MOMENTS = ["t-28", "t+7"]
# Input groups, as a reader would name them. A column belongs to the first group whose test it passes.
GROUPS = {
    "YouTube trailer comments": lambda c: c.startswith("yt_") or c == "has_youtube",
    "Wikipedia, English and Japanese": lambda c: c.startswith(("wiki_en_", "wiki_ja_")),
    "Wikipedia, Indian languages": lambda c: c.startswith("wiki_india_") or c == "has_india_article",
    "Reddit posts": lambda c: c.startswith("reddit_"),
    "Similar past titles (lookalike)": lambda c: c == "lookalike",
    "Prequel's India index": lambda c: c in ("prequel_label", "has_prequel_label"),
    "Genre, format, source, audience": lambda c: c.startswith(("genre_", "format_", "source_", "audience_"))
                                                 or c == "is_sequel",
}
FULL = "All inputs"


def forecasts(features, titles, labels, train_ids, target_ids):
    """{variant: Series of Blend forecasts for target_ids}: all inputs, then without each group present."""
    X_train, X_target, _ = stacked_inputs(features, titles, labels, train_ids, target_ids)
    y = labels.loc[train_ids]
    out = {FULL: Blend().fit(X_train, y).predict(X_target)}
    for name, member in GROUPS.items():
        drop = [c for c in X_train.columns if member(c)]
        if drop:
            out[name] = Blend().fit(X_train.drop(columns=drop), y).predict(X_target.drop(columns=drop))
    return out


def rho(pred, actual):
    both = pd.concat([pred, actual], axis=1).dropna()
    return spearmanr(both.iloc[:, 0], both.iloc[:, 1]).statistic if len(both) >= MIN_TARGET else np.nan


def ablate(titles, labels, features):
    split = split_of(titles)
    train = split.index[split == "train"].intersection(labels.index)
    validate = split.index[split == "validate"].intersection(labels.index)
    guard_test(validate, titles, final=False)
    results = {}
    for moment in MOMENTS:
        val = forecasts(features[moment], titles, labels, train, validate)
        seasons = {}
        for _, fold_train, fold_target in rolling_folds(titles):
            fold_train, fold_target = fold_train.intersection(labels.index), fold_target.intersection(labels.index)
            if len(fold_train) < MIN_TRAIN or len(fold_target) < MIN_TARGET:
                continue
            for variant, pred in forecasts(features[moment], titles, labels, fold_train, fold_target).items():
                seasons.setdefault(variant, []).append(rho(pred, labels.loc[fold_target]))
        rows = {}
        for variant, pred in val.items():
            low, high = bootstrap(pred, labels.loc[validate])
            rows[variant] = {"spearman": rho(pred, labels.loc[validate]), "low": low, "high": high,
                             "rolling": float(np.nanmean(seasons[variant])) if seasons.get(variant) else np.nan,
                             "seasons": len(seasons.get(variant, []))}
        full = rows[FULL]
        for variant, row in rows.items():
            row["loss"] = full["spearman"] - row["spearman"]
            row["rolling_loss"] = full["rolling"] - row["rolling"]
        results[moment] = {"titles": len(validate), "variants": rows}
    return results


def report(results):
    lines = ["# What each signal is worth", "", "Generated by `python -m yosoku.ablation`; do not edit by hand.", "",
             "The Blend refitted without one group of inputs at a time. *Loss* is how much rank correlation it gives "
             "up against all inputs: on the 2024 validation titles, and averaged over the rolling seasons. "
             "A positive loss means the group helps.", ""]
    for moment, result in results.items():
        lines += [f"## {moment} ({result['titles']} validation titles)", "",
                  "| Inputs | Spearman 2024 (95% interval) | Loss 2024 | Rolling seasons | Loss rolling |",
                  "| --- | --- | --- | --- | --- |"]
        for variant, r in result["variants"].items():
            name = variant if variant == FULL else f"without {variant}"
            lines.append(f"| {name} | {fmt(r['spearman'])} ({fmt(r['low'])} to {fmt(r['high'])}) | "
                         f"{'' if variant == FULL else fmt(r['loss'])} | {fmt(r['rolling'])} over {r['seasons']} | "
                         f"{'' if variant == FULL else fmt(r['rolling_loss'])} |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_folder_arguments(parser)
    args = parser.parse_args()
    data_dir, out_dir = folder(args.data_dir), folder(args.out_dir)
    titles, labels, features = prepare(data_dir, out_dir)
    results = ablate(titles, labels, features)
    (out_dir / "reports").mkdir(parents=True, exist_ok=True)
    (out_dir / "reports" / "ablation.md").write_text(report(results), encoding="utf-8")
    (out_dir / "reports" / "ablation.json").write_text(
        json.dumps(results, indent=1, default=lambda x: None if pd.isna(x) else float(x)), encoding="utf-8")
    print("Wrote reports/ablation.md")


if __name__ == "__main__":
    main()
